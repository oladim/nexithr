// Builds the role catalog from content/roles/*.js:
//   1. lib/roleCatalog.js                         — light, client-safe labels & structure
//   2. supabase/migrations/0029_role_catalog.sql  — schema + seed (areas, role-levels,
//      staff-only interview playbooks, draft training courses)
// Run:  node scripts/build-roles.mjs
import fs from "fs";
import path from "path";
import crypto from "crypto";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const AREA_ORDER = ["support", "software", "data", "product", "cloud", "security"];
const LEVELS = ["junior", "mid", "senior"];

const load = async (f) => (await import(pathToFileURL(path.join(ROOT, "content/roles", f)).href)).default;
const shared = (await import(pathToFileURL(path.join(ROOT, "lib/interviewShared.js")).href)).default;
const areas = [];
for (const k of AREA_ORDER) areas.push(await load(`${k}.js`));

const LEVEL_LABEL = Object.fromEntries(LEVELS.map((l) => [l, shared.levels[l].label]));
const baseKey = (a, r) => `${a.key}-${r.id}`;
const roleKey = (a, r, l) => `${baseKey(a, r)}-${l}`;
const roleTitle = (r, l) => `${r.title} (${LEVEL_LABEL[l]})`;

// ---------- 1. client-safe catalog ----------
const catAreas = areas.map((a, i) => ({ key: a.key, title: a.title, summary: a.summary, sort: i }));
const catRoles = [];
areas.forEach((a, ai) => a.roles.forEach((r, ri) => LEVELS.forEach((l, li) => {
  const L = r.levels[l];
  catRoles.push({
    key: roleKey(a, r, l), area: a.key, base: baseKey(a, r), baseTitle: r.title, level: l,
    title: roleTitle(r, l), minYears: L.minYears, summary: r.summary, focus: L.focus,
    sort: ai * 100 + ri * 10 + li,
  });
})));

const catalogJs = `// GENERATED by scripts/build-roles.mjs — do not edit by hand.
// Light, client-safe role catalog (areas → roles → levels). Full role content
// (interview guides, curricula) lives in the database, seeded by 0029.

export const LEVELS = ${JSON.stringify(LEVELS.map((l) => ({ key: l, ...shared.levels[l] })), null, 2)};

export const AREAS = ${JSON.stringify(catAreas, null, 2)};

export const ROLES = ${JSON.stringify(catRoles, null, 2)};

export const CATALOG_LABELS = Object.fromEntries(ROLES.map((r) => [r.key, r.title]));
const BASE_TITLES = Object.fromEntries(ROLES.map((r) => [r.base, r.baseTitle]));
const AREA_TITLES = Object.fromEntries(AREAS.map((a) => [a.key, a.title]));
const LEGACY = { software: "software", data: "data", product: "product", cloud: "cloud", security: "security", support: "support" };

// "support-sysadmin-mid" → "support-sysadmin"; legacy area keys map to themselves.
export function baseKeyOf(key) {
  if (!key) return "";
  const m = /^([a-z]+-[a-z]+)-(junior|mid|senior)$/.exec(key);
  return m ? m[1] : key;
}
export function levelOf(key) {
  const m = /-(junior|mid|senior)$/.exec(key || "");
  return m ? m[1] : null;
}
export function areaOf(key) {
  if (!key) return "";
  if (LEGACY[key]) return key;
  return key.split("-")[0];
}
export function areaTitle(areaKey) { return AREA_TITLES[areaKey] || areaKey; }
export function baseTitleOf(key) { return BASE_TITLES[baseKeyOf(key)] || null; }
// Every role_key whose training applies to this target role.
export function courseKeysFor(key) {
  const b = baseKeyOf(key);
  return [...new Set([key, b].filter(Boolean))];
}
`;
fs.writeFileSync(path.join(ROOT, "lib/roleCatalog.js"), catalogJs);

// ---------- 2. SQL ----------
// Every text value is base64-encoded and decoded inside Postgres. The SQL
// then contains no apostrophes, quotes, semicolons or dollar signs inside
// values, so no SQL editor (or copy/paste "smart quote" conversion) can
// break a statement — however the content is worded.
const b64 = (t) => Buffer.from(String(t), "utf8").toString("base64");
const q = (s) => (s == null ? "null" : `convert_from(decode('${b64(s)}','base64'),'UTF8')`);
const arr = (a) => `array(select jsonb_array_elements_text(${q(JSON.stringify(a || []))}::jsonb))`;
const js = (o) => `${q(JSON.stringify(o))}::jsonb`;
const uuid = (s) => {
  const h = crypto.createHash("md5").update(s).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};
const MIG = path.join(ROOT, "supabase/migrations");
// Remove files from earlier generator versions.
for (const f of fs.readdirSync(MIG)) if (/^00(29|3\d)_role/.test(f)) fs.unlinkSync(path.join(MIG, f));

// ----- 0029: schema + areas -----
let sql = `-- =====================================================================
-- 0029 — Role catalog schema: 6 areas → 24 roles → 3 levels.
-- GENERATED by scripts/build-roles.mjs. Run this first, then 0030–0035
-- (one file per area: its role-levels, staff-only interview playbooks and
-- draft training courses).
--   * role_areas        — the six areas (public).
--   * role_requirements — + area, base role, level, responsibilities, tools,
--                         certifications. One row per role-level.
--   * role_playbooks    — STAFF-ONLY interview material (admins + interviewers).
-- The original one-per-area roles (software, data, …) are kept for candidates
-- who chose them, marked kind = 'area' and hidden from new pickers.
-- Idempotent.
-- =====================================================================

` + `create table if not exists public.role_areas (
  key     text primary key,
  title   text not null,
  summary text,
  sort    int not null default 0
);
alter table public.role_areas enable row level security;
drop policy if exists role_areas_select on public.role_areas;
create policy role_areas_select on public.role_areas for select to anon, authenticated using (true);
drop policy if exists role_areas_write on public.role_areas;
create policy role_areas_write on public.role_areas for all to authenticated using (public.is_admin()) with check (public.is_admin());

alter table public.role_requirements add column if not exists kind             text not null default 'role';
alter table public.role_requirements add column if not exists area_key         text;
alter table public.role_requirements add column if not exists base_role        text;
alter table public.role_requirements add column if not exists base_title       text;
alter table public.role_requirements add column if not exists level            text;
alter table public.role_requirements add column if not exists focus            text;
alter table public.role_requirements add column if not exists responsibilities text[] not null default '{}';
alter table public.role_requirements add column if not exists tools            text[] not null default '{}';
alter table public.role_requirements add column if not exists certifications   text[] not null default '{}';
alter table public.role_requirements add column if not exists sort             int not null default 0;
create index if not exists role_requirements_area_idx on public.role_requirements(area_key, sort);

update public.role_requirements set kind = 'area', area_key = role_key
 where role_key in ('software','data','product','cloud','security','support') and kind <> 'area';

create table if not exists public.role_playbooks (
  role_key           text primary key references public.role_requirements(role_key) on delete cascade,
  competencies       jsonb not null default '[]',
  ai_blueprint       jsonb not null default '{}',
  professional_guide jsonb not null default '{}',
  hr_guide           jsonb not null default '{}',
  updated_by         uuid references public.profiles(id) on delete set null,
  updated_at         timestamptz not null default now()
);
alter table public.role_playbooks enable row level security;
-- Interview material is for staff only: admins and interviewers.
drop policy if exists role_playbooks_select on public.role_playbooks;
create policy role_playbooks_select on public.role_playbooks for select to authenticated
  using (public.is_admin() or public.role_of(auth.uid()) = 'interviewer');
drop policy if exists role_playbooks_write on public.role_playbooks;
create policy role_playbooks_write on public.role_playbooks for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

` + `-- ---------- areas ----------\n`;
for (const a of catAreas) {
  sql += `insert into public.role_areas (key, title, summary, sort) values (${q(a.key)}, ${q(a.title)}, ${q(a.summary)}, ${a.sort}) on conflict (key) do nothing;\n`;
}
fs.writeFileSync(path.join(MIG, "0029_role_catalog.sql"), sql);
const sizes = [`0029 ${(sql.length / 1024).toFixed(0)} KB`];

// ----- 0030–0035: one file per area -----
areas.forEach((a, ai) => {
  const num = String(30 + ai).padStart(4, "0");
  let s = `-- =====================================================================
-- ${num} — Role catalog: ${a.title} (run after 0029).
-- GENERATED by scripts/build-roles.mjs from content/roles/${a.key}.js.
-- ${a.roles.map((r) => r.title).join(", ")} — each Junior / Mid-level / Senior,
-- with staff-only interview playbooks and draft (unapproved) training courses.
-- Idempotent: fixed ids, and nothing overwrites edits made in the admin.
-- =====================================================================

`;
  a.roles.forEach((r, ri) => {
    s += `-- ===== ${r.title} =====\n`;
    LEVELS.forEach((l, li) => {
      const L = r.levels[l];
      const key = roleKey(a, r, l);
      const sort = AREA_ORDER.indexOf(a.key) * 100 + ri * 10 + li;
      const desc = `${r.summary}\n\nAt this level: ${L.focus}`;
      s += `insert into public.role_requirements (role_key, title, description, required_skills, min_experience, enabled, kind, area_key, base_role, base_title, level, focus, responsibilities, tools, certifications, sort)
values (${q(key)}, ${q(roleTitle(r, l))}, ${q(desc)}, ${arr(L.skills)}, ${L.minYears}, true, 'role', ${q(a.key)}, ${q(baseKey(a, r))}, ${q(r.title)}, ${q(l)}, ${q(L.focus)}, ${arr(L.responsibilities)}, ${arr(L.tools)}, ${arr(L.certifications)}, ${sort})
on conflict (role_key) do nothing;\n`;
      const blueprint = { level: l, levelLabel: LEVEL_LABEL[l], focus: L.focus, topics: L.aiTopics, scenarios: L.aiScenarios, expectations: L.aiExpectations };
      const pro = { questions: L.proQuestions, competencies: r.competencies }; // + shared anchors/notes merged at runtime (lib/interviewShared.js)
      const hr = { roleScenarios: r.hrScenarios }; // + shared HR questions merged at runtime
      s += `insert into public.role_playbooks (role_key, competencies, ai_blueprint, professional_guide, hr_guide) values (${q(key)}, ${js(r.competencies)}, ${js(blueprint)}, ${js(pro)}, ${js(hr)}) on conflict (role_key) do nothing;\n`;
    });
    ["foundational", "intensive"].forEach((lvl, ci) => {
      const C = r.curriculum[lvl];
      const cid = uuid(`nexit-course:${baseKey(a, r)}:${lvl}`);
      s += `insert into public.specific_courses (id, role_key, title, summary, level, duration, sort, approved) values ('${cid}', ${q(baseKey(a, r))}, ${q(C.title)}, ${q(C.summary)}, ${q(lvl)}, ${q(C.duration)}, ${ci}, false) on conflict (id) do nothing;\n`;
      C.modules.forEach((m, mi) => {
        const mid = uuid(`nexit-module:${baseKey(a, r)}:${lvl}:${mi}`);
        const maxScore = m.type === "quiz" ? 100 : (m.maxScore || 0);
        s += `insert into public.course_modules (id, course_id, title, type, content, max_score, sort, questions, approved) values ('${mid}', '${cid}', ${q(m.title)}, ${q(m.type)}, ${q(m.content || null)}, ${maxScore}, ${mi}, ${m.questions ? js(m.questions) : "null"}, false) on conflict (id) do nothing;\n`;
      });
    });
    s += "\n";
  });
  const fname = `${num}_roles_${a.key}.sql`;
  fs.writeFileSync(path.join(MIG, fname), s);
  sizes.push(`${num} ${(s.length / 1024).toFixed(0)} KB`);
});
console.log(`catalog: ${catAreas.length} areas, ${catRoles.length} role-levels; ${sizes.join(", ")}`);
